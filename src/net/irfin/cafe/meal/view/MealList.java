    private void btnRefreshActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRefreshActionPerformed
        List<Meal> listMakanan;
        
        try {
            // Baca dari database record2 MealCategory
            var repo = new MealRepo(DatabaseConnection.getConnection());
            listMakanan = repo.getAll();
        }
        catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error saat mengakses data: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // tampilkan ke JTable
        var tm = (DefaultTableModel) tblMeal.getModel();
        tm.setRowCount(0);      // Kosongkan dahulu baris2 data
        for (Meal m : listMakanan) {
            var barisData = new Object[] {
                m.getId(),
                m.getCategory().getName(),
                m.getName() 
            };
            
            tm.addRow(barisData);
        }
        tblMeal.setModel(tm);
    }//GEN-LAST:event_btnRefreshActionPerformed

