    private void menuItemEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuItemEditActionPerformed
        // Ambil baris yg dipilih user
        int idxBarisDipilih = tblMeal.getSelectedRow();
        if (idxBarisDipilih == -1) {
            JOptionPane.showMessageDialog(this, "Select row you want to edit");
            return;
        }
        idxBarisDipilih = tblMeal.convertRowIndexToModel(idxBarisDipilih);
        
        // Ambil ID dan Nama dari data yg dipilih
        int idMeal = (int) tblMeal.getModel().getValueAt(idxBarisDipilih, COL_ID);

        var dlgEdit = new MealUpdateDlg(null, idMeal);
        dlgEdit.setLocationRelativeTo(MainApp.getMainWindow());
        dlgEdit.setVisible(true);
        
        if (dlgEdit.isClosedByOk()) {
            btnRefreshActionPerformed(evt);
        }
    }//GEN-LAST:event_menuItemEditActionPerformed

    private void tblMealMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMealMouseClicked
        // Cek apakah user double click dan dgn left button
        if (SwingUtilities.isLeftMouseButton(evt) && evt.getClickCount() > 1) {
            
            // Ambil baris yg dipilih user
            int idxBarisDipilih = tblMeal.getSelectedRow();
            if (idxBarisDipilih == -1) {
                JOptionPane.showMessageDialog(this, "Select row you want to edit");
                return;
            }
            idxBarisDipilih = tblMeal.convertRowIndexToModel(idxBarisDipilih);
            
            // Ambil ID dan Nama dari data yg dipilih
            int idMeal = (int) tblMeal.getModel().getValueAt(idxBarisDipilih, COL_ID);

            var dlgView = new MealViewDlg(null, idMeal);
            dlgView.setLocationRelativeTo(MainApp.getMainWindow());
            dlgView.setVisible(true);
        }
    }//GEN-LAST:event_tblMealMouseClicked

